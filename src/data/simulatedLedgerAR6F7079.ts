/**
 * Calculates yearly summaries dynamically from the underlying ledger transactions.
 */
export function calculateYearlyLedgerSummaries(transactions: BankTransaction[], baseOpeningBalance = INITIAL_OPENING_BALANCE): YearlySummary[] {
  const sorted = [...transactions].sort((a, b) => new Date(a.timestamp).getTime() - new Date(b.timestamp).getTime());
  const yearSet = new Set<number>();
  sorted.forEach((t) => {
    yearSet.add(new Date(t.timestamp).getFullYear());
  });
  const years = Array.from(yearSet).sort((a, b) => a - b);

  let runningOpening = baseOpeningBalance;
  const summaries: YearlySummary[] = [];

  for (const yr of years) {
    const yrTxs = sorted.filter((t) => new Date(t.timestamp).getFullYear() === yr);
    const credits = yrTxs.filter((t) => t.direction === 'credit');
    const debits = yrTxs.filter((t) => t.direction === 'debit');

    const totalCredits = credits.reduce((sum, t) => sum + t.amount, 0);
    const totalDebits = debits.reduce((sum, t) => sum + t.amount, 0);
    const netChange = Number((totalCredits - totalDebits).toFixed(2));
    const closingBalance = Number((runningOpening + netChange).toFixed(2));

    summaries.push({
      year: yr,
      openingBalance: runningOpening,
      totalCredits: Number(totalCredits.toFixed(2)),
      creditCount: credits.length,
      totalDebits: Number(totalDebits.toFixed(2)),
      debitCount: debits.length,
      netChange,
      closingBalance,
      transactionCount: yrTxs.length,
    });

    runningOpening = closingBalance;
  }

  return summaries;
}

/**
 * Prepares statement result for a given date range and category dynamically from the underlying ledger.
 */
export function prepareReconciledStatement(
  transactions: BankTransaction[],
  account: BankAccount,
  user: BankingUser,
  startDate: string,
  endDate: string,
  category = 'Entire Account Statement',
  deliveryMethod: 'download' | 'email' = 'download'
): StatementPreparationResult {
  const sorted = [...transactions].sort((a, b) => new Date(a.timestamp).getTime() - new Date(b.timestamp).getTime());

  // Period transactions
  const periodTxs = sorted.filter((t) => {
    const d = t.timestamp.slice(0, 10);
    return d >= startDate && d <= endDate;
  });

  // Calculate opening balance before period
  const priorTxs = sorted.filter((t) => t.timestamp.slice(0, 10) < startDate);
  let openingBalance = INITIAL_OPENING_BALANCE;
  if (priorTxs.length > 0) {
    openingBalance = priorTxs[priorTxs.length - 1].balanceAfter;
  } else if (periodTxs.length > 0) {
    const first = periodTxs[0];
    openingBalance = first.direction === 'credit'
      ? first.balanceAfter - first.amount
      : first.balanceAfter + first.amount;
  }

  // Filter category if applicable
  let matchingTxs = periodTxs;
  if (category === 'Incoming Transfers (Inflows)') {
    matchingTxs = periodTxs.filter((t) => t.direction === 'credit');
  } else if (category === 'Outgoing Transfers (Outflows)') {
    matchingTxs = periodTxs.filter((t) => t.direction === 'debit');
  } else if (category === 'Utility Bill Payments') {
    matchingTxs = periodTxs.filter((t) => t.category.includes('Utility') || t.category.includes('Fee'));
  }

  const credits = matchingTxs.filter((t) => t.direction === 'credit');
  const debits = matchingTxs.filter((t) => t.direction === 'debit');
  const totalCredits = Number(credits.reduce((sum, t) => sum + t.amount, 0).toFixed(2));
  const totalDebits = Number(debits.reduce((sum, t) => sum + t.amount, 0).toFixed(2));
  const netChange = Number((totalCredits - totalDebits).toFixed(2));
  const closingBalance = periodTxs.length > 0
    ? periodTxs[periodTxs.length - 1].balanceAfter
    : openingBalance;

  const now = new Date();
  const serverTimeFormatted = now.toLocaleString('en-US', {
    timeZone: 'America/Chicago',
    year: 'numeric',
    month: 'short',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
    hour12: true,
  });

  return {
    account,
    user: {
      id: user.id,
      fullName: `${user.firstName} ${user.lastName}`.trim(),
      email: user.email,
      phone: user.phoneNumber,
      address: `${user.residentialAddress.street}, ${user.residentialAddress.city}, ${user.residentialAddress.state} ${user.residentialAddress.zipCode}`,
    },
    startDate,
    endDate,
    category,
    deliveryMethod,
    serverTimestamp: now.toISOString(),
    serverTimeFormatted: `${serverTimeFormatted} CDT`,
    serverTimezone: 'CDT (UTC-05:00)',
    auditReference: `SIM-REC-${startDate.replace(/-/g, '')}-${endDate.replace(/-/g, '')}`,
    summary: {
      openingBalance: Number(openingBalance.toFixed(2)),
      closingBalance: Number(closingBalance.toFixed(2)),
      totalDebits,
      debitCount: debits.length,
      totalCredits,
      creditCount: credits.length,
      netChange,
      transactionCount: matchingTxs.length,
    },
    transactions: matchingTxs,
  };
}
